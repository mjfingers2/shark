import { parseWorkspaceKey } from '../../../shared/workspace-scope'
import { getRepoIdFromWorktreeId } from '../../../shared/worktree/id'
import { isAutoGeneratedCreatureBranchName } from '../../../shared/source-control/ai/naming/branch-name-from-work'
import type { FirstWorkBranchRenameDeps } from './first-work-branch-rename'

type SessionTitleDeps = Pick<
  FirstWorkBranchRenameDeps,
  'getCurrentDisplayName' | 'setDisplayName' | 'onRenamed' | 'isPendingFirstAgentMessageRename'
>

const OWNER_LIMIT = 500
// Which chat named each session, and the title it gave. In memory only: after a restart a
// session already has its title and is never renamed again.
const titleOwners = new Map<string, { sessionId: string; title: string }>()

/**
 * Shark names a session after what its first chat is about. The chat's own naming reads the
 * first request and writes a short title (first a clipped seed, then the generated one); the
 * session follows that chat's title while it still carries a generated creature name or the
 * title this follower set. Later chats in the session, such as context hand-offs, and names
 * the user typed are left alone.
 */
export function followFirstChatTitle(
  worktreeId: string,
  sessionId: string,
  chatName: string | undefined,
  deps: SessionTitleDeps
): boolean {
  const title = chatName?.trim()
  if (!title) {
    return false
  }
  const current = deps.getCurrentDisplayName(worktreeId)?.trim() ?? ''
  const owner = titleOwners.get(worktreeId)
  if (owner) {
    if (owner.sessionId !== sessionId || owner.title !== current) {
      return false
    }
  } else if (
    !isAutoGeneratedCreatureBranchName(current) &&
    deps.isPendingFirstAgentMessageRename?.(worktreeId) !== true
  ) {
    return false
  }
  titleOwners.delete(worktreeId)
  titleOwners.set(worktreeId, { sessionId, title })
  for (const oldest of titleOwners.keys()) {
    if (titleOwners.size <= OWNER_LIMIT) {
      break
    }
    titleOwners.delete(oldest)
  }
  if (title === current) {
    return false
  }
  deps.setDisplayName(worktreeId, title)
  const isFolder = parseWorkspaceKey(worktreeId)?.type === 'folder'
  deps.onRenamed(isFolder ? worktreeId : getRepoIdFromWorktreeId(worktreeId))
  return true
}

export function resetSessionTitleOwnersForTest(): void {
  titleOwners.clear()
}
