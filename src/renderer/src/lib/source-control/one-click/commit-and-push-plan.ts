import { isAutoGeneratedCreatureBranchName } from '../../../../../shared/source-control/ai/naming/branch-name-from-work'

export type CommitAndPushPlan = 'commit-and-push' | 'push-only' | 'nothing'

/** Commit when files changed; push when that commit, earlier commits, or an unpublished branch need it. */
export function decideCommitAndPush(input: {
  changedFiles: number
  hasUpstream: boolean
  ahead: number
}): CommitAndPushPlan {
  if (input.changedFiles > 0) {
    return 'commit-and-push'
  }
  return !input.hasUpstream || input.ahead > 0 ? 'push-only' : 'nothing'
}

/** Used when AI cannot write the message: the session's name says what the work was. */
export function fallbackCommitMessage(displayName: string | undefined, branch: string): string {
  const name = displayName?.trim()
  // A generated creature name (sawfish) says nothing about the work.
  if (name && !isAutoGeneratedCreatureBranchName(name)) {
    return name
  }
  const shortBranch =
    branch
      .replace(/^refs\/heads\//, '')
      .split('/')
      .pop() ?? ''
  return shortBranch ? `Update ${shortBranch.replace(/-/g, ' ')}` : 'Update'
}
